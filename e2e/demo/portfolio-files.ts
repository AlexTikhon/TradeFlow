import { createHash } from 'node:crypto';

/*
 * The four PDF files of the portfolio showcase (portfolio.ts): small, valid single-page PDFs
 * built here, byte for byte the same on every run, so their SHA-256 is known in advance. Their
 * text is synthetic and says so; it names no person and carries no voyage reference or id, which
 * differ between runs. Each expected checksum is pinned below and checked when this module loads:
 * a change to the generator that changes the bytes fails loudly instead of moving the target.
 */

/** Escapes text for a PDF literal string; the text itself is plain ASCII. */
function pdfString(text: string): string {
  if (!/^[\x20-\x7e]*$/.test(text)) throw new Error(`Not printable ASCII: ${text}`);
  return `(${text.replace(/[\\()]/g, (c) => `\\${c}`)})`;
}

/** A one-page A4 PDF 1.4 with `lines` in Helvetica, its cross-reference offsets computed. */
export function syntheticPdf(lines: readonly string[]): Buffer {
  const [title = '', ...rest] = lines;
  const text = [
    'BT',
    '/F1 16 Tf',
    '72 770 Td',
    `${pdfString(title)} Tj`,
    '/F1 11 Tf',
    ...rest.flatMap((line) => ['0 -22 Td', `${pdfString(line)} Tj`]),
    'ET',
  ].join('\n');
  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] ' +
      '/Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>',
    `<< /Length ${Buffer.byteLength(text, 'latin1')} >>\nstream\n${text}\nendstream`,
  ];
  let body = '%PDF-1.4\n';
  const offsets: number[] = [];
  objects.forEach((object, index) => {
    offsets.push(Buffer.byteLength(body, 'latin1'));
    body += `${index + 1} 0 obj\n${object}\nendobj\n`;
  });
  const xref = Buffer.byteLength(body, 'latin1');
  body += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (const offset of offsets) body += `${offset.toString().padStart(10, '0')} 00000 n \n`;
  body += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return Buffer.from(body, 'latin1');
}

export const sha256 = (bytes: Buffer) => createHash('sha256').update(bytes).digest('hex');

export interface ShowcaseFile {
  fileName: string;
  bytes: Buffer;
  /** The pinned SHA-256 of `bytes`, lowercase hex. */
  sha256: string;
}

const FOOTER = [
  'Synthetic file for the TradeFlow portfolio demo.',
  'Fictional content: not a real trade document. No personal data.',
];

function showcaseFile(fileName: string, lines: string[], expected: string): ShowcaseFile {
  const bytes = syntheticPdf([...lines, '', ...FOOTER]);
  const actual = sha256(bytes);
  if (actual !== expected) {
    throw new Error(
      `${fileName}: the generated bytes hash to ${actual}, not the pinned ${expected}`,
    );
  }
  return { fileName, bytes, sha256: expected };
}

