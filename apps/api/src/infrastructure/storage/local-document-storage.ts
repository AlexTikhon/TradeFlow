import { randomUUID } from 'node:crypto';
import { createWriteStream } from 'node:fs';
import { mkdir, open, rename, rm } from 'node:fs/promises';
import { join } from 'node:path';
import type { Readable } from 'node:stream';
import { pipeline } from 'node:stream/promises';
import {
  DocumentStorage,
  type StagedObject,
  StoredObjectMissingError,
} from './document-storage.js';

/** Keys and staging ids are UUIDs generated here; nothing else may name a file. */
const ID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

function checkedId(id: string): string {
  if (!ID.test(id)) {
    throw new Error('Not a storage id generated by this storage');
  }
  return id;
}

const isMissing = (error: unknown) =>
  error instanceof Error && 'code' in error && error.code === 'ENOENT';

/**
 * Document storage on the local filesystem, under one private root directory:
 *
 * - `staging/<uuid>.part` while an upload is being received (exclusive create, owner-only);
 * - `objects/<uuid>` once it is kept, moved there by a rename within the same filesystem, so a
 *   stored object is either complete or absent.
 *
 * Bytes are flushed to disk before the staged file is closed, so a promoted object survives a
 * crash. The directory entry of the rename is not fsynced: after a power loss a just-promoted
 * object can vanish, in which case its database row (committed after the rename) names a
 * missing object, which downloads report as a data error. The root must not be served by any
 * web server; nothing here makes it reachable over HTTP.
 */
export class LocalDocumentStorage extends DocumentStorage {
  private readonly stagingDirectory: string;
  private readonly objectDirectory: string;

  constructor(root: string) {
    super();
    this.stagingDirectory = join(root, 'staging');
    this.objectDirectory = join(root, 'objects');
  }

  async stage(source: Readable): Promise<StagedObject> {
    await mkdir(this.stagingDirectory, { recursive: true, mode: 0o700 });
    const staged = { id: randomUUID() };
    const path = this.stagingPath(staged);
    try {
      await pipeline(source, createWriteStream(path, { flags: 'wx', mode: 0o600, flush: true }));
    } catch (error) {
      // The source failed (aborted, too large, unreadable) or the disk did: keep nothing.
      source.destroy();
      await rm(path, { force: true });
      throw error;
    }
    return staged;
  }

  async promote(staged: StagedObject): Promise<string> {
    await mkdir(this.objectDirectory, { recursive: true, mode: 0o700 });
    const key = randomUUID();
    await rename(this.stagingPath(staged), this.objectPath(key));
    return key;
  }

  async discard(staged: StagedObject): Promise<void> {
    await rm(this.stagingPath(staged), { force: true });
  }

  async read(key: string): Promise<Readable> {
    try {
      const handle = await open(this.objectPath(key), 'r');
      return handle.createReadStream();
    } catch (error) {
      if (isMissing(error)) throw new StoredObjectMissingError(key);
      throw error;
    }
  }

  async remove(key: string): Promise<void> {
    await rm(this.objectPath(key), { force: true });
  }

  private stagingPath(staged: StagedObject): string {
    return join(this.stagingDirectory, `${checkedId(staged.id)}.part`);
  }

  private objectPath(key: string): string {
    return join(this.objectDirectory, checkedId(key));
  }
}
