import { randomUUID } from 'node:crypto';
import { Readable } from 'node:stream';
import {
  DeleteObjectCommand,
  GetObjectCommand,
  ListObjectsV2Command,
  S3Client,
} from '@aws-sdk/client-s3';
import { Upload } from '@aws-sdk/lib-storage';
import { Logger, type OnModuleDestroy } from '@nestjs/common';
import type { S3StorageConfig } from '../../config/app-config.js';
import {
  DocumentStorage,
  type StagedObject,
  StoredObjectMissingError,
} from './document-storage.js';

const ID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

/** Private, immutable-by-convention objects. Only the database makes an upload reachable. */
export class S3DocumentStorage extends DocumentStorage implements OnModuleDestroy {
  private readonly logger = new Logger(S3DocumentStorage.name);
  readonly client: S3Client;

  constructor(readonly config: S3StorageConfig) {
    super();
    this.client = new S3Client({
      region: config.region,
      ...(config.endpoint && { endpoint: config.endpoint }),
      forcePathStyle: config.forcePathStyle,
      // Credentials come from the standard SDK chain (including workload roles).
      maxAttempts: 3,
      requestHandler: { connectionTimeout: 5_000, requestTimeout: 30_000 },
      requestChecksumCalculation: 'WHEN_REQUIRED',
      responseChecksumValidation: 'WHEN_REQUIRED',
    });
  }

  objectKey(id: string): string {
    if (!ID.test(id)) throw new Error('Not a storage id generated by this storage');
    return `${this.config.prefix}objects/${id}`;
  }

  async stage(source: Readable): Promise<StagedObject> {
    const staged = { id: randomUUID() };
    // Some application transforms expose a running `size` counter. lib-storage mistakes that
    // for a fixed Blob size and rejects multipart completion. Give it a plain unknown-size stream.
    const body = Readable.from(source, { objectMode: false });
    const upload = new Upload({
      client: this.client,
      params: {
        Bucket: this.config.bucket,
        Key: this.objectKey(staged.id),
        Body: body,
        ContentType: 'application/pdf',
      },
      queueSize: 1,
      partSize: 5 * 1024 * 1024,
      leavePartsOnError: false,
    });
    try {
      await upload.done();
      return staged;
    } catch (error) {
      body.destroy();
      source.destroy();
      // lib-storage aborts known multipart uploads. A completed PUT/CompleteMultipartUpload
      // whose response was lost can still have left a whole object; compensate by its known id.
      await this.discard(staged).catch(() => {
        this.logger.error(
          `Could not remove failed upload ${staged.id}; reconcile this possible orphan and incomplete multipart uploads.`,
        );
      });
      throw error;
    }
  }

  override promote(staged: StagedObject): Promise<string> {
    this.objectKey(staged.id);
    // No rename/copy: stage already persisted the bytes. Publication is the subsequent SQL
    // transaction. This avoids an extra distributed operation with an ambiguous copy result.
    return Promise.resolve(staged.id);
  }

  async discard(staged: StagedObject): Promise<void> {
    await this.remove(staged.id);
  }

  async read(key: string): Promise<Readable> {
    const request = new GetObjectCommand({ Bucket: this.config.bucket, Key: this.objectKey(key) });
    try {
      const { Body } = await this.client.send(request);
      if (!(Body instanceof Readable)) throw new Error('S3 returned no readable object body');
      return Body;
    } catch (error) {
      // Do not disguise access denied, a missing bucket or a provider outage as a missing file.
      if (error instanceof Error && error.name === 'NoSuchKey')
        throw new StoredObjectMissingError(key);
      throw error;
    }
  }

  async remove(key: string): Promise<void> {
    await this.client.send(
      new DeleteObjectCommand({ Bucket: this.config.bucket, Key: this.objectKey(key) }),
    );
  }

  /** Maintenance inventory only; never exposed by an HTTP endpoint. Includes possible orphans. */
  async *keys(): AsyncGenerator<string> {
    let continuation: string | undefined;
    const prefix = `${this.config.prefix}objects/`;
    do {
      const page = await this.client.send(
        new ListObjectsV2Command({
          Bucket: this.config.bucket,
          Prefix: prefix,
          ...(continuation && { ContinuationToken: continuation }),
        }),
      );
      for (const object of page.Contents ?? []) {
        const id = object.Key?.slice(prefix.length);
        if (!id || !ID.test(id)) throw new Error('Unexpected key in document object prefix');
        yield id;
      }
      continuation = page.NextContinuationToken;
    } while (continuation);
  }

  onModuleDestroy(): void {
    this.client.destroy();
  }
}
