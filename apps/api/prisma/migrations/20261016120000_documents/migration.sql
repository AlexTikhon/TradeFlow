-- Documents are accepted only for the instruction's current revision, and only for a document
-- type that revision requires. The instruction row is share-locked, so it cannot move on to a
-- new revision until this transaction ends: a revision given meanwhile waits for it, and an
-- upload that waited for a revision sees the new current revision and is refused.
CREATE FUNCTION "documents_require_open_revision"(instruction uuid, revision integer, document "document_type")
RETURNS void LANGUAGE plpgsql AS $$
DECLARE
  current_number integer;
  requirements jsonb;
BEGIN
  SELECT "current_revision_number" INTO current_number
  FROM "documentary_instructions" WHERE "id" = instruction
  FOR SHARE;
  IF current_number IS DISTINCT FROM revision THEN
    RAISE EXCEPTION 'documents: only the current revision of an instruction accepts documents'
      USING ERRCODE = 'restrict_violation';
  END IF;
  SELECT r."requirements" INTO requirements
  FROM "documentary_instruction_revisions" AS r
  WHERE r."instruction_id" = instruction AND r."revision_number" = revision;
  IF requirements IS NULL
     OR NOT requirements @> jsonb_build_array(jsonb_build_object('document', document::text)) THEN
    RAISE EXCEPTION 'documents: revision % does not require %', revision, document
      USING ERRCODE = 'restrict_violation';
  END IF;
END;
$$;

-- How a document may change, for every writer. It is created at version 1, for an open revision
-- that requires it. Afterwards each upload advances the version by exactly one; what the
-- document belongs to never changes.
CREATE FUNCTION "documents_guard"() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    IF NEW."current_version_number" <> 1 THEN
      RAISE EXCEPTION 'documents: a document starts at version 1'
        USING ERRCODE = 'restrict_violation';
    END IF;
    PERFORM "documents_require_open_revision"(NEW."instruction_id", NEW."revision_number", NEW."document_type");
    RETURN NEW;
  END IF;
  IF (NEW."id", NEW."voyage_id", NEW."trade_contract_id", NEW."instruction_id", NEW."revision_number",
      NEW."document_type", NEW."created_at")
     IS DISTINCT FROM (OLD."id", OLD."voyage_id", OLD."trade_contract_id", OLD."instruction_id",
      OLD."revision_number", OLD."document_type", OLD."created_at") THEN
    RAISE EXCEPTION 'documents: what a document belongs to cannot change'
      USING ERRCODE = 'restrict_violation';
  END IF;
  IF NEW."current_version_number" <> OLD."current_version_number" + 1 THEN
    RAISE EXCEPTION 'documents: versions are numbered one after another'
      USING ERRCODE = 'restrict_violation';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER "documents_guard"
BEFORE INSERT OR UPDATE ON "documents"
FOR EACH ROW EXECUTE FUNCTION "documents_guard"();

-- The current version exists by the time the transaction commits: a document is never created,
-- or advanced to a new version, without writing that version.
CREATE FUNCTION "documents_require_version"() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM "document_versions"
    WHERE "document_id" = NEW."id" AND "version_number" = NEW."current_version_number"
  ) THEN
    RAISE EXCEPTION 'documents: the current version % does not exist', NEW."current_version_number"
      USING ERRCODE = 'foreign_key_violation';
  END IF;
  RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER "documents_require_version"
AFTER INSERT OR UPDATE ON "documents"
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION "documents_require_version"();

-- A version is written only as its document's current version, right after the document advanced
-- to it (so numbers have no gaps), and only while the document's revision is still open. This is
-- what refuses a replacement against a superseded revision, whoever writes it.
CREATE FUNCTION "document_versions_require_current"() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  document record;
BEGIN
  SELECT "instruction_id", "revision_number", "document_type", "current_version_number" INTO document
  FROM "documents" WHERE "id" = NEW."document_id"
  FOR SHARE;
  IF document."current_version_number" IS DISTINCT FROM NEW."version_number" THEN
    RAISE EXCEPTION 'document_versions: only the current version of a document can be written'
      USING ERRCODE = 'restrict_violation';
  END IF;
  PERFORM "documents_require_open_revision"(document."instruction_id", document."revision_number", document."document_type");
  RETURN NEW;
END;
$$;

CREATE TRIGGER "document_versions_current"
BEFORE INSERT ON "document_versions"
FOR EACH ROW EXECUTE FUNCTION "document_versions_require_current"();

